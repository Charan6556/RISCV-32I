class riscv_coverage extends uvm_subscriber #(riscv_transaction);

    `uvm_component_utils(riscv_coverage)

    bit [31:0] instr_mem [0:1023];

    // instruction coverage
    covergroup instr_cg with function sample(bit [31:0] instr);

        option.per_instance = 1;

        cp_instr : coverpoint instr {

            // R type
            wildcard bins ADD  = {32'b0000000_?????_?????_000_?????_0110011};
            wildcard bins SUB  = {32'b0100000_?????_?????_000_?????_0110011};
            wildcard bins SLL  = {32'b0000000_?????_?????_001_?????_0110011};
            wildcard bins SLT  = {32'b0000000_?????_?????_010_?????_0110011};
            wildcard bins SLTU = {32'b0000000_?????_?????_011_?????_0110011};
            wildcard bins XOR  = {32'b0000000_?????_?????_100_?????_0110011};
            wildcard bins SRL  = {32'b0000000_?????_?????_101_?????_0110011};
            wildcard bins SRA  = {32'b0100000_?????_?????_101_?????_0110011};
            wildcard bins OR   = {32'b0000000_?????_?????_110_?????_0110011};
            wildcard bins AND  = {32'b0000000_?????_?????_111_?????_0110011};

            // I type
            wildcard bins ADDI  = {32'b????????????_?????_000_?????_0010011};
            wildcard bins SLTI  = {32'b????????????_?????_010_?????_0010011};
            wildcard bins SLTIU = {32'b????????????_?????_011_?????_0010011};
            wildcard bins XORI  = {32'b????????????_?????_100_?????_0010011};
            wildcard bins ORI   = {32'b????????????_?????_110_?????_0010011};
            wildcard bins ANDI  = {32'b????????????_?????_111_?????_0010011};

            wildcard bins SLLI =
                {32'b0000000_?????_?????_001_?????_0010011};

            wildcard bins SRLI =
                {32'b0000000_?????_?????_101_?????_0010011};

            wildcard bins SRAI =
                {32'b0100000_?????_?????_101_?????_0010011};

            // loads
            wildcard bins LB  = {32'b????????????_?????_000_?????_0000011};
            wildcard bins LH  = {32'b????????????_?????_001_?????_0000011};
            wildcard bins LW  = {32'b????????????_?????_010_?????_0000011};
            wildcard bins LBU = {32'b????????????_?????_100_?????_0000011};
            wildcard bins LHU = {32'b????????????_?????_101_?????_0000011};

            // stores
            wildcard bins SB =
                {32'b????????????_?????_000_?????_0100011};

            wildcard bins SH =
                {32'b????????????_?????_001_?????_0100011};

            wildcard bins SW =
                {32'b????????????_?????_010_?????_0100011};

            // branches
            wildcard bins BEQ =
                {32'b????????????_?????_000_?????_1100011};

            wildcard bins BNE =
                {32'b????????????_?????_001_?????_1100011};

            wildcard bins BLT =
                {32'b????????????_?????_100_?????_1100011};

            wildcard bins BGE =
                {32'b????????????_?????_101_?????_1100011};

            wildcard bins BLTU =
                {32'b????????????_?????_110_?????_1100011};

            wildcard bins BGEU =
                {32'b????????????_?????_111_?????_1100011};

            // upper and jump
            wildcard bins LUI =
                {32'b????????????????????_?????_0110111};

            wildcard bins AUIPC =
                {32'b????????????????????_?????_0010111};

            wildcard bins JAL =
                {32'b????????????????????_?????_1101111};

            wildcard bins JALR =
                {32'b????????????_?????_000_?????_1100111};

        }
    endgroup

    // pipeline coverage
    covergroup pipeline_cg with function sample(
        bit       stall_s,
        bit       redirect_s,
        bit [1:0] forward_a_s,
        bit [1:0] forward_b_s,
        bit       dmem_req_s,
        bit [3:0] dmem_wstrb_s
    );

        option.per_instance = 1;

        cp_stall : coverpoint stall_s {
            bins no_stall = {0};
            bins stall    = {1};
        }

        cp_redirect : coverpoint redirect_s {
            bins no_redirect = {0};
            bins redirect    = {1};
        }

        cp_forward_a : coverpoint forward_a_s {

            bins no_forward = {2'b00};
            bins mem_wb     = {2'b01};
            bins ex_mem     = {2'b10};

            illegal_bins invalid = {2'b11};
        }

        cp_forward_b : coverpoint forward_b_s {

            bins no_forward = {2'b00};
            bins mem_wb     = {2'b01};
            bins ex_mem     = {2'b10};

            illegal_bins invalid = {2'b11};
        }

        cp_dmem_req : coverpoint dmem_req_s {
            bins no_access = {0};
            bins access    = {1};
        }

        cp_wstrb : coverpoint dmem_wstrb_s iff (dmem_req_s) {

            bins read = {4'b0000};

            bins byte_write[] = {
                4'b0001,
                4'b0010,
                4'b0100,
                4'b1000
            };

            bins half_write[] = {
                4'b0011,
                4'b0110,
                4'b1100
            };

            bins word_write = {4'b1111};

        }

        forward_cross : cross cp_forward_a, cp_forward_b;
    endgroup

    function new(string name = "riscv_coverage", uvm_component parent = null);
        super.new(name, parent);

        instr_cg    = new();
        pipeline_cg = new();
    endfunction

    function void write(riscv_transaction t);
        bit [31:0] commit_instr;

        // save instruction
        instr_mem[t.pc[11:2]] = t.instr;

        // committed instruction coverage
        if (t.commit_valid) begin
            commit_instr = instr_mem[t.commit_pc[11:2]];

            instr_cg.sample(commit_instr);
        end

        // pipeline coverage
        pipeline_cg.sample(
            t.stall,
            t.redirect,
            t.forward_a,
            t.forward_b,
            t.dmem_req,
            t.dmem_wstrb
        );
    endfunction

    function void report_phase(uvm_phase phase);
        super.report_phase(phase);

        `uvm_info("COV",
            $sformatf(
                "Instruction Coverage = %0.2f%%",
                instr_cg.get_inst_coverage()
            ),
            UVM_NONE
        )

        `uvm_info("COV",
            $sformatf(
                "Pipeline Coverage = %0.2f%%",
                pipeline_cg.get_inst_coverage()
            ),
            UVM_NONE
        )
    endfunction
endclass
